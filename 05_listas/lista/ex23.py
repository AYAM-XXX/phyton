# 23. (Controle de Qualidade): Uma fábrica mede o diâmetro de peças industriais em uma
# lista: . Exiba a amplitude das medidas (a diferença
# entre a maior peça e a menor peça) usando funções embutidas.

diametro = [10.2, 9.8, 10.5, 11.0, 9.9]
print(f"diametro das medidas: {(max(diametro) - min(diametro)):.2f}")